#Дано целое число А.
# #Проверить истинность высказывания: «Число А является положительным».
while True:
    try:
        a = int(input("Введите число: "))
        break
    except ValueError:
        print("Введено не число! Попробуйте снова")

if a > 0:
    print("Число положительное")
else:
    print("Число отрицательное")


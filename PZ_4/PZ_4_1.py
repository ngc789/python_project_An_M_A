# Даны два целых числа A и B (A < B). Вывести в порядке возрастания
# все целые числа, расположенные между A и B (включая сами числа A и B),
# а также количество N этих чисел.
a,b = input("Введите 1 число: "), input("Введите 2 число: ")
while type(a) != int:
    try:
        a = int(a)
    except ValueError:
        print("Неправильное введенный символ . Попробуйте снова")
while type(b) != int:
    try:
        b = int(b)
    except ValueError:
        print("Неправильн введеный символ . Попробуйте снова")
k = 0
while a <= b:
    print(a)
    a += 1
    k += 1
print("Количество чисел :", k)
# Даны положительные числа A, B, C. На прямоугольнике размера A х B
# размещено максимально возможное количество квадратов со стороной C
# (без наложений). Найти количество квадратов, размещенных на
# прямоугольнике. Операции умножения и деления не использовать.
a, b, c = (
    input("Введите 1 сторону прямоугольника: "),
    input("Введите 2 сторону прямоугольника: "),
    input("Введите сторону квадрата: ")
)
while type (a) != float:
    try:
        a = float(a)
        if a<= 0:
            print("Число должно быть положительным . Попробуйте снова")
            a = input("Введите 1 сторону прямоугольника: ")
    except ValueError:
        print("Неправильно введённый символ . Попробуйте снова")
        a = input("Введите 1 сторону прямоугольника: ")
while type (b) != float:
    try:
        b = float(b)
        if b<= 0:
            print("Число должно быть положительным . Попробуйте снова")
            b = input("Введите 2 сторону прямоугольника: ")
    except ValueError:
        print("Неправильно введённый символ . Попробуйте снова")
        b = input("Введите 2 сторону прямоугольника: ")
while type (c) != float:
    try:
        c = float(c)
        if c<= 0:
            print("Число должно быть положительным . Попробуйте снова")
            c = input("Введите сторону квадрата: ")
    except ValueError:
        print("Неправильно введённый символ . Попробуйте снова")
        c = input("Введите сторону квадрата: ")
count_a = 0
while a >= c:
    a -= c
    count_a += 1
count_b = 0
while b >= c:
    b -= c
    count_b += 1
total = 0
q = 0
while q < count_b:
    total += count_a
    q += 1
print("Количество квадратов: ", total)
